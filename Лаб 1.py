# Ввод данных
S = float(input("Сумма S: "))
v1 = float(input("Вклад 1: "))
v2 = float(input("Вклад 2: "))
v3 = float(input("Вклад 3: "))

# Расчет общего вклада
всего = v1 + v2 + v3

# Расчет и вывод долей
print("Доля 1:", S * v1 / всего)
print("Доля 2:", S * v2 / всего)
print("Доля 3:", S * v3 / всего)

